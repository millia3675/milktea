export const dailyQuestionCount = questions.length;
export function dailyQuestion(date = today()) {
  if (!validDate(date)) throw new Error("INVALID_QUESTION_DATE");
  const day = Math.floor((Date.parse(`${date}T00:00:00Z`) - Date.UTC(2026, 8, 17)) / 86400000);
  return { date, text: questions[((day % questions.length) + questions.length) % questions.length] };
}
export function validQuestion(q) {
  return q == null || (typeof q === "object" && validDate(q.date) && q.date <= today() &&
    typeof q.text === "string" && q.text.trim().length > 0 && [...q.text].length <= 200);
}
